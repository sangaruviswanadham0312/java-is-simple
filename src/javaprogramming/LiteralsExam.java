package javaprogramming;

public class LiteralsExam {

	public static void main(String[] args) {
		int a=100;
		double b=29.5;
		char c='a';
		String d="chitti";
		boolean e=true;
		long f=234343353355L;
		System.out.println("integer literal:"+a);
		System.out.println("double literal:"+b);
		System.out.println("character literal:"+c);
		System.out.println("string literal:"+d);
		System.out.println("boolean literal:"+e);
		System.out.println("long literal:"+f);

	}

}
